import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
const base=process.argv[2] || 'http://127.0.0.1:3108'
const report=JSON.parse(await readFile(process.argv[3] || 'output/seo-foundation-check.json','utf8'))
for(const page of report.pages) {
  assert.equal(page.status,200,`${page.path}: HTTP status`)
  assert.ok(page.title && page.description,`${page.path}: title/description absent`)
  const canonical=new URL(page.canonical)
  assert.equal(canonical.origin,'https://michellescomputer.com',`${page.path}: canonical origin`)
  assert.equal(canonical.pathname,page.path,`${page.path}: canonical points to another page`)
  assert.ok(!page.ogImage.includes('placeholder'),`${page.path}: placeholder sharing image`)
  assert.ok(page.types.includes('Person') && page.types.includes('WebSite'),`${page.path}: entity graph absent`)
  assert.ok(!page.types.includes('INVALID_JSON'),`${page.path}: malformed structured data`)
}
const book=report.pages.find(page=>page.path==='/girly-guide-to-ai')
assert.ok(book.types.includes('Book'));assert.ok(book.types.includes('FAQPage'));assert.equal(book.illustrations,0)
assert.ok(report.pages.find(page=>page.path.includes('/learn/how-to-')).types.includes('Article'))
assert.match(report.pages.find(page=>page.path==='/learn/submit').robots,/noindex/)
const sitemap=report.resources.find(resource=>resource.path==='/sitemap.xml')
assert.equal(sitemap.status,200)
assert.ok(sitemap.urls.includes('https://michellescomputer.com/projects/rag-in-practice'))
assert.ok(sitemap.urls.includes('https://michellescomputer.com/projects/delta-stock-pitch'))
assert.ok(!sitemap.urls.some(url=>url.includes('/learn/submit') || url.includes('/begin')))
assert.match(report.resources.find(resource=>resource.path==='/robots.txt').text,/OAI-SearchBot/)
for(const path of ['/begin','/begin/openai','/openaibeta']) {
 const response=await fetch(base+path);const html=await response.text()
 assert.equal(response.status,200)
 assert.match(html,/<meta[^>]+name="robots"[^>]+content="[^"]*noindex/,`${path}: proposal is indexable`)
}
const image=await fetch(base+'/opengraph-image');assert.equal(image.status,200);assert.match(image.headers.get('content-type'),/image\/png/)
const png=Buffer.from(await image.arrayBuffer());assert.equal(png.readUInt32BE(16),1200);assert.equal(png.readUInt32BE(20),630)
assert.ok(sitemap.urls.includes('https://michellescomputer.com/learn/authors/leesha-mogha'))
assert.ok(!sitemap.urls.some(url=>url.includes('/girly-guide-to-ai/read')))
const proof=await fetch(base+'/girly-guide-to-ai?preview=full');const proofHtml=await proof.text()
assert.equal(proof.status,200);assert.ok(!proofHtml.includes('>Full text<'))
assert.ok(!proofHtml.includes('data-nosnippet'), 'search landing page must not contain scrambled preview prose')
assert.ok(Buffer.byteLength(proofHtml)<150000, 'book landing HTML must stay compact')
assert.ok(proofHtml.includes('/_next/image?url='),'book cover must use responsive image delivery')
const artwork=await fetch(base+'/_next/image?url=%2Ffinds%2Frandom-eyes.png&w=640&q=75',{headers:{accept:'image/webp'}})
assert.equal(artwork.status,200,'optimized Learn artwork must load')
assert.match(artwork.headers.get('content-type'),/image\/webp/)
assert.ok((await artwork.arrayBuffer()).byteLength<200000,'mobile artwork should not download the full source PNG')
const reader=await fetch(base+'/girly-guide-to-ai/read?preview=full');const readerHtml=await reader.text()
assert.equal(reader.status,200)
assert.match(readerHtml,/<meta[^>]+name="robots"[^>]+content="[^"]*noindex/)
assert.ok(readerHtml.includes('Reading preview'));assert.ok(!readerHtml.includes('>Full text<'))
assert.ok((readerHtml.match(/data-source-page=/g)||[]).length<230)
const prepared=JSON.parse(await readFile('data/books/girly-guide-ai.preview.json','utf8'))
let figures=0
for(const chapter of prepared.chapters) {
  const response=await fetch(`${base}/api/guide/chapters/${chapter.id}?preview=full`)
  assert.equal(response.status,200)
  assert.equal(response.headers.get('x-robots-tag'),'noindex')
  const payload=await response.json()
  assert.deepEqual(payload.chapter,chapter,'chapter endpoint must serve only the prepared public preview')
  figures+=Object.values(payload.figures).flat().length
}
assert.equal(figures,230,'all original illustrations remain available in the reader')
assert.equal((await fetch(base+'/api/guide/chapters/not-a-chapter')).status,404)
const author=await fetch(base+'/learn/authors/leesha-mogha');const authorHtml=await author.text()
assert.equal(author.status,200);assert.ok(authorHtml.includes('ProfilePage'));assert.ok(authorHtml.includes('AI Alignment'))
assert.equal((await fetch(base+'/_private/girly-guide-ai.full.json')).status,404)
console.log(JSON.stringify({pages:report.pages.length,originalFigures:figures,bookLandingBytes:Buffer.byteLength(proofHtml),initialReaderBytes:Buffer.byteLength(readerHtml),sharingImage:'1200x630 PNG',productionProofLocked:true,sitemapAndRobots:'passed',utilityNoindex:'passed'},null,2))
